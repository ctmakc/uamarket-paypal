export type Lang = "en" | "uk";
export const LANGS: Lang[] = ["en", "uk"];

export function isLang(v: string | undefined): v is Lang {
  return v === "en" || v === "uk";
}

/** Build a localized href: English has no prefix, Ukrainian lives under /uk. */
export function href(lang: Lang, path: string): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  if (lang === "en") return clean === "/" ? "/" : clean;
  return clean === "/" ? "/uk" : `/uk${clean}`;
}

/** Pick a localized content field from the API (falls back to English). */
export function pick(lang: Lang, en: string | null | undefined, uk: string | null | undefined): string {
  if (lang === "uk" && uk) return uk;
  return en ?? "";
}

